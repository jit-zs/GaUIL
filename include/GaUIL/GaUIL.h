void gauil_setUnloadTextureFn(gauil_UnloadTextureCallback* callback);
void gauil_setDrawTextureFn(gauil_DrawTextureCallback* callback);

void gauil_setDrawUserData(void* userData);
void gauil_setDefaultFontFromFile(const char* file);
void gauil_setDefaultFontFromMemory(const uint8_t* data, size_t size);
void gauil_init();
void gauil_cleanup();
void gauil_update();
