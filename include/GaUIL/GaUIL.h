bool gauil_loadFontFromMemory(const uint8_t* data, size_t size, const char* referenceName);

gauil_Layout gauil_scaleWithOpposingAxis(gauil_Layout layout);
void gauil_pushSubRect(gauil_Layout2D position, gauil_Layout2D size);
void gauil_popSubRect();

bool gauil_button(const char* text, gauil_Layout2D position, gauil_Layout2D size);
